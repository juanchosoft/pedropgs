<?php

declare(strict_types=1);

namespace Pgs\Reports;

use Pgs\Auth\Principal;
use Pgs\Core\Db;
use Pgs\Core\Exceptions\ForbiddenException;

final class ExpensesReportPdf extends PdfBase
{
    public function render(Principal $p, int $unitId, string $from, string $to, string $lang = 'en'): array
    {
        if ($p->isUnitAdmin()) {
            throw new ForbiddenException('Access denied: Property administrators cannot view expense reports.');
        }

        $pdo = Db::pdo();

        // Load unit info
        $uStmt = $pdo->prepare('SELECT id, nombre, ubicacion FROM tbl_unidades WHERE id = :id');
        $uStmt->execute([':id' => $unitId]);
        $unit = $uStmt->fetch(\PDO::FETCH_ASSOC);
        $unitName = $unit ? (string) $unit['nombre'] : "Property #{$unitId}";

        // Query expenses for unit and date range
        $stmt = $pdo->prepare(
            "SELECT e.*,
                    TRIM(CONCAT(IFNULL(u.nombre, ''), ' ', IFNULL(u.apellido, ''))) AS created_by_name
             FROM tec_expenses e
             LEFT JOIN tec_usuarios u ON u.id = e.created_by_user_id
             WHERE e.unidad_id = :u
               AND e.purchase_date BETWEEN :f1 AND :f2
             ORDER BY e.purchase_date DESC, e.id DESC"
        );
        $stmt->execute([
            ':u' => $unitId,
            ':f1' => $from,
            ':f2' => $to,
        ]);
        $expenses = $stmt->fetchAll(\PDO::FETCH_ASSOC);

        // Fetch line items for each expense
        $itemsByExpense = [];
        if (!empty($expenses)) {
            $expIds = array_column($expenses, 'id');
            $inClause = implode(',', array_map('intval', $expIds));
            $itemsStmt = $pdo->query("SELECT * FROM tec_expense_items WHERE expense_id IN ({$inClause}) ORDER BY id ASC");
            while ($row = $itemsStmt->fetch(\PDO::FETCH_ASSOC)) {
                $itemsByExpense[(int) $row['expense_id']][] = $row;
            }
        }

        $pdf = $this->createTcpdf("Expenses Report - {$unitName}", "Internal Expenses Report from {$from} to {$to}");

        // --- COVER PAGE ---
        $pdf->AddPage();
        $logoPath = dirname(__DIR__, 4) . '/assets/img/pgsinfo.png';
        if (is_file($logoPath)) {
            $pdf->Image($logoPath, 70, 35, 70, 0, 'PNG');
        }

        $pdf->SetY(85);
        $pdf->SetFont('helvetica', 'B', 22);
        $pdf->SetTextColor(11, 15, 25);
        $pdf->Cell(0, 12, 'PROPERTY EXPENSES & COSTS REPORT', 0, 1, 'C');

        // Red line accent #E10600
        $pdf->SetDrawColor(225, 6, 0);
        $pdf->SetLineWidth(1.2);
        $pdf->Line(60, $pdf->GetY(), 150, $pdf->GetY());
        $pdf->Ln(6);

        $pdf->SetFont('helvetica', 'B', 15);
        $pdf->SetTextColor(225, 6, 0);
        $pdf->Cell(0, 9, strtoupper($unitName), 0, 1, 'C');

        $pdf->SetFont('helvetica', '', 12);
        $pdf->SetTextColor(80, 80, 80);
        $pdf->Cell(0, 8, "Period: {$from} to {$to}", 0, 1, 'C');

        // Totals calculation
        $totalExpenses = 0.0;
        $totalPending = 0.0;
        $totalInvoiced = 0.0;
        $count = count($expenses);

        foreach ($expenses as $exp) {
            if ($exp['billing_status'] === 'void') {
                continue;
            }
            $t = (float) ($exp['total_amount'] ?? $exp['total'] ?? 0.0);
            $totalExpenses += $t;
            if ($exp['billing_status'] === 'invoiced') {
                $totalInvoiced += $t;
            } else {
                $totalPending += $t;
            }
        }

        $pdf->Ln(6);
        $pdf->SetFont('helvetica', 'B', 11);
        $pdf->SetTextColor(11, 15, 25);
        $pdf->Cell(0, 7, 'Expense Totals Breakdown:', 0, 1, 'C');

        $pdf->SetFont('helvetica', '', 10);
        $pdf->SetTextColor(80, 80, 80);
        $pdf->Cell(0, 6, "Total Recorded Expenses: {$count}", 0, 1, 'C');
        $pdf->Cell(0, 6, sprintf('Pending Billing: $%.2f   |   Already Invoiced: $%.2f', $totalPending, $totalInvoiced), 0, 1, 'C');

        $pdf->SetFont('helvetica', 'B', 12);
        $pdf->SetTextColor(225, 6, 0);
        $pdf->Cell(0, 8, sprintf('Total Expenses: $%.2f', $totalExpenses), 0, 1, 'C');

        $pdf->SetY(220);
        $pdf->SetFont('helvetica', '', 10);
        $pdf->SetTextColor(120, 120, 120);
        $pdf->Cell(0, 6, 'Generated by: ' . ($p->isSystemAdmin() ? 'Super Administrator' : 'Field Operations Staff'), 0, 1, 'C');
        $pdf->Cell(0, 6, 'Generated Date: ' . date('Y-m-d H:i:s T'), 0, 1, 'C');
        $pdf->Cell(0, 6, 'STRICTLY CONFIDENTIAL - INTERNAL PGS USE ONLY', 0, 1, 'C');

        // --- EXPENSES CONTENT ---
        $pdf->AddPage();
        $this->renderHeaderBar($pdf, $unitName, $from, $to);
        $pdf->SetY(32);

        if (empty($expenses)) {
            $pdf->SetFont('helvetica', 'I', 12);
            $pdf->SetTextColor(120, 120, 120);
            $pdf->Cell(0, 15, 'No expenses found for this property in the selected date range.', 0, 1, 'C');
        } else {
            foreach ($expenses as $exp) {
                if ($pdf->GetY() > 235) {
                    $pdf->AddPage();
                    $this->renderHeaderBar($pdf, $unitName, $from, $to);
                    $pdf->SetY(32);
                }

                $expId = (int) $exp['id'];
                $code = (string) $exp['code'];
                $vendor = (string) ($exp['vendor'] ?? 'N/A');
                $receipt = (string) ($exp['receipt_number'] ?? 'N/A');
                $purchaseDate = (string) $exp['purchase_date'];
                $status = strtoupper((string) ($exp['billing_status'] ?? 'PENDING'));
                $total = (float) ($exp['total_amount'] ?? $exp['total'] ?? 0.0);
                $createdBy = !empty($exp['created_by_name']) ? (string) $exp['created_by_name'] : 'System';

                // Expense header bar
                $pdf->SetFillColor(245, 247, 250);
                $pdf->Rect(15, $pdf->GetY(), 180, 8, 'F');
                $pdf->SetFont('helvetica', 'B', 10);
                $pdf->SetTextColor(225, 6, 0);
                $pdf->Cell(35, 8, ' ' . $code, 0, 0, 'L');

                $pdf->SetFont('helvetica', 'B', 10);
                $pdf->SetTextColor(11, 15, 25);
                $pdf->Cell(65, 8, 'Vendor: ' . substr($vendor, 0, 30), 0, 0, 'L');

                $pdf->SetFont('helvetica', '', 9);
                $pdf->SetTextColor(80, 80, 80);
                $pdf->Cell(40, 8, "Date: {$purchaseDate}", 0, 0, 'L');

                $pdf->SetFont('helvetica', 'B', 9);
                if ($status === 'INVOICED') {
                    $pdf->SetTextColor(22, 101, 52);
                } elseif ($status === 'VOID') {
                    $pdf->SetTextColor(150, 150, 150);
                } else {
                    $pdf->SetTextColor(202, 138, 4);
                }
                $pdf->Cell(0, 8, $status . ' ', 0, 1, 'R');

                // Metadata row
                $pdf->SetFont('helvetica', '', 8.5);
                $pdf->SetTextColor(100, 100, 100);
                $pdf->SetX(18);
                $pdf->Cell(0, 5, "Receipt #: {$receipt}   |   Staff: {$createdBy}", 0, 1, 'L');

                // Items table
                $items = $itemsByExpense[$expId] ?? [];
                if (!empty($items)) {
                    $pdf->SetFont('helvetica', 'B', 8);
                    $pdf->SetTextColor(80, 80, 80);
                    $pdf->SetX(20);
                    $pdf->Cell(95, 5, 'Item Description', 0, 0, 'L');
                    $pdf->Cell(20, 5, 'Qty', 0, 0, 'C');
                    $pdf->Cell(25, 5, 'Unit Price', 0, 0, 'R');
                    $pdf->Cell(30, 5, 'Line Total', 0, 1, 'R');

                    $pdf->SetFont('helvetica', '', 8);
                    $pdf->SetTextColor(40, 40, 40);
                    foreach ($items as $it) {
                        $lineTot = (float) ($it['line_total'] ?? $it['total_price'] ?? 0.0);
                        $pdf->SetX(20);
                        $pdf->Cell(95, 4.5, substr((string) $it['description'], 0, 50), 0, 0, 'L');
                        $pdf->Cell(20, 4.5, (string) $it['quantity'], 0, 0, 'C');
                        $pdf->Cell(25, 4.5, sprintf('$%.2f', (float) $it['unit_price']), 0, 0, 'R');
                        $pdf->Cell(30, 4.5, sprintf('$%.2f', $lineTot), 0, 1, 'R');
                    }
                }

                // Expense total line
                $pdf->SetFont('helvetica', 'B', 9);
                $pdf->SetTextColor(11, 15, 25);
                $pdf->SetX(130);
                $pdf->Cell(35, 6, 'Expense Total:', 0, 0, 'R');
                $pdf->SetTextColor(225, 6, 0);
                $pdf->Cell(25, 6, sprintf('$%.2f', $total), 0, 1, 'R');

                $pdf->Ln(3);
                $pdf->SetDrawColor(220, 220, 220);
                $pdf->SetLineWidth(0.3);
                $pdf->Line(15, $pdf->GetY(), 195, $pdf->GetY());
                $pdf->Ln(3);
            }
        }

        return $this->saveToStorage($pdf, 'expenses_report_' . $unitId);
    }

    private function renderHeaderBar(\TCPDF $pdf, string $unitName, string $from, string $to): void
    {
        $pdf->Rect(0, 0, 210, 22, 'F', [], [11, 15, 25]);
        $pdf->Rect(0, 22, 210, 2, 'F', [], [225, 6, 0]);

        $pdf->SetXY(15, 6);
        $pdf->SetFont('helvetica', 'B', 11);
        $pdf->SetTextColor(255, 255, 255);
        $pdf->Cell(120, 10, 'PGS CENTRUM  |  ' . strtoupper($unitName) . '  |  EXPENSES (INTERNAL)', 0, 0, 'L');

        $pdf->SetFont('helvetica', '', 9);
        $pdf->SetTextColor(220, 220, 220);
        $pdf->Cell(0, 10, "{$from} to {$to}", 0, 0, 'R');
    }
}
