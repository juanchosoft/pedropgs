<?php

declare(strict_types=1);

namespace Pgs\Reports;

use Pgs\Auth\Principal;
use Pgs\Core\Db;

final class ActivityReportPdf extends PdfBase
{
    public function render(Principal $p, int $unitId, string $from, string $to, string $lang = 'en'): array
    {
        $pdo = Db::pdo();

        // Load unit info
        $uStmt = $pdo->prepare('SELECT id, nombre, ubicacion FROM tbl_unidades WHERE id = :id');
        $uStmt->execute([':id' => $unitId]);
        $unit = $uStmt->fetch(\PDO::FETCH_ASSOC);
        $unitName = $unit ? (string) $unit['nombre'] : "Property #{$unitId}";

        // Load activity records from tbl_fotos
        $q = "SELECT f.*,
                     TRIM(CONCAT(IFNULL(u.nombre, ''), ' ', IFNULL(u.apellido, ''))) AS usuario_nombre
              FROM tbl_fotos f
              LEFT JOIN tec_usuarios u ON u.id = f.tbl_usuario_id
              WHERE f.tbl_unidad_id = :u
                AND f.dtcreate BETWEEN :f1 AND :f2
              ORDER BY f.dtcreate ASC, f.id ASC";
        $stmt = $pdo->prepare($q);
        $stmt->execute([
            ':u' => $unitId,
            ':f1' => $from . ' 00:00:00',
            ':f2' => $to . ' 23:59:59',
        ]);
        $records = $stmt->fetchAll(\PDO::FETCH_ASSOC);

        $pdf = $this->createTcpdf("Activity Report - {$unitName}", "Daily Activity Report from {$from} to {$to}");

        // --- COVER PAGE ---
        $pdf->AddPage();
        $logoPath = dirname(__DIR__, 4) . '/assets/img/pgsinfo.png';
        if (is_file($logoPath)) {
            $pdf->Image($logoPath, 70, 35, 70, 0, 'PNG');
        }

        $pdf->SetY(85);
        $pdf->SetFont('helvetica', 'B', 22);
        $pdf->SetTextColor(11, 15, 25); // #0B0F19
        $pdf->Cell(0, 12, 'DAILY ACTIVITY REPORT', 0, 1, 'C');

        // Red line accent #E10600
        $pdf->SetDrawColor(225, 6, 0);
        $pdf->SetLineWidth(1.2);
        $pdf->Line(60, $pdf->GetY(), 150, $pdf->GetY());
        $pdf->Ln(6);

        $pdf->SetFont('helvetica', 'B', 15);
        $pdf->SetTextColor(225, 6, 0);
        $pdf->Cell(0, 9, strtoupper($unitName), 0, 1, 'C');

        $pdf->SetFont('helvetica', '', 12);
        $pdf->SetTextColor(80, 80, 80);
        $pdf->Cell(0, 8, "Period: {$from} to {$to}", 0, 1, 'C');
        $pdf->Cell(0, 8, 'Total Jobs / Logs Recorded: ' . count($records), 0, 1, 'C');

        $pdf->SetY(220);
        $pdf->SetFont('helvetica', '', 10);
        $pdf->SetTextColor(120, 120, 120);
        $pdf->Cell(0, 6, 'Generated by: ' . ($p->isSystemAdmin() ? 'Super Administrator' : 'Authorized Staff'), 0, 1, 'C');
        $pdf->Cell(0, 6, 'Generated Date: ' . date('Y-m-d H:i:s T'), 0, 1, 'C');
        $pdf->Cell(0, 6, 'Confidential Property Report - PGS Centrum', 0, 1, 'C');

        // --- RECORDS PAGES ---
        if (empty($records)) {
            $pdf->AddPage();
            $this->renderHeaderBar($pdf, $unitName, $from, $to);
            $pdf->SetY(60);
            $pdf->SetFont('helvetica', 'I', 13);
            $pdf->SetTextColor(100, 100, 100);
            $pdf->Cell(0, 15, 'No activity logs or maintenance jobs recorded for this period.', 0, 1, 'C');
        } else {
            $webRoot = dirname(__DIR__, 4);
            foreach ($records as $idx => $rec) {
                $pdf->AddPage();
                $this->renderHeaderBar($pdf, $unitName, $from, $to);

                $pdf->SetY(32);
                $jobNum = $idx + 1;
                $tech = !empty($rec['usuario_nombre']) ? $rec['usuario_nombre'] : 'Field Technician';
                $dateRecorded = !empty($rec['dtcreate']) ? substr((string) $rec['dtcreate'], 0, 16) : 'N/A';
                $comments = !empty($rec['comentario']) ? (string) $rec['comentario'] : 'Routine maintenance activity executed successfully.';

                $pdf->SetFont('helvetica', 'B', 12);
                $pdf->SetTextColor(11, 15, 25);
                $pdf->Cell(100, 7, "Job #{$jobNum} of " . count($records), 0, 0, 'L');
                $pdf->SetFont('helvetica', '', 10);
                $pdf->SetTextColor(90, 90, 90);
                $pdf->Cell(0, 7, "Recorded: {$dateRecorded}", 0, 1, 'R');

                $pdf->SetFont('helvetica', 'B', 10);
                $pdf->SetTextColor(11, 15, 25);
                $pdf->Cell(28, 6, 'Technician:', 0, 0);
                $pdf->SetFont('helvetica', '', 10);
                $pdf->Cell(0, 6, $tech, 0, 1);

                $pdf->SetFont('helvetica', 'B', 10);
                $pdf->Cell(28, 6, 'Description:', 0, 0);
                $pdf->SetFont('helvetica', '', 10);
                $pdf->MultiCell(0, 6, $comments, 0, 'L');
                $pdf->Ln(4);

                // Before and After Images
                $yBeforeImg = $pdf->GetY();
                $colW = 85;

                // Photo Before
                $pdf->SetFont('helvetica', 'B', 10);
                $pdf->SetTextColor(225, 6, 0);
                $pdf->Cell($colW, 6, 'BEFORE WORK', 0, 0, 'C');
                $pdf->Cell(10, 6, '', 0, 0);
                $pdf->Cell($colW, 6, 'AFTER WORK', 0, 1, 'C');

                $imgY = $pdf->GetY() + 2;
                $fotoAntes = !empty($rec['fotoantes']) ? $this->resolveImagePath($webRoot, (string) $rec['fotoantes']) : null;
                $fotoDespues = !empty($rec['fotodespues']) ? $this->resolveImagePath($webRoot, (string) $rec['fotodespues']) : null;

                if ($fotoAntes && is_file($fotoAntes)) {
                    $pdf->Image($fotoAntes, 15, $imgY, $colW, 95, '', '', '', true, 300, '', false, false, 1);
                } else {
                    $pdf->Rect(15, $imgY, $colW, 95, 'F', [], [245, 245, 245]);
                    $pdf->SetXY(15, $imgY + 40);
                    $pdf->SetFont('helvetica', 'I', 9);
                    $pdf->SetTextColor(150, 150, 150);
                    $pdf->Cell($colW, 6, 'No before photo available', 0, 0, 'C');
                }

                if ($fotoDespues && is_file($fotoDespues)) {
                    $pdf->Image($fotoDespues, 110, $imgY, $colW, 95, '', '', '', true, 300, '', false, false, 1);
                } else {
                    $pdf->Rect(110, $imgY, $colW, 95, 'F', [], [245, 245, 245]);
                    $pdf->SetXY(110, $imgY + 40);
                    $pdf->SetFont('helvetica', 'I', 9);
                    $pdf->SetTextColor(150, 150, 150);
                    $pdf->Cell($colW, 6, 'No after photo available', 0, 0, 'C');
                }
            }
        }

        return $this->saveToStorage($pdf, 'activity_report_' . $unitId);
    }

    private function renderHeaderBar(\TCPDF $pdf, string $unitName, string $from, string $to): void
    {
        // Dark header bar #0B0F19
        $pdf->Rect(0, 0, 210, 22, 'F', [], [11, 15, 25]);
        // Red accent line #E10600
        $pdf->Rect(0, 22, 210, 2, 'F', [], [225, 6, 0]);

        $pdf->SetXY(15, 6);
        $pdf->SetFont('helvetica', 'B', 11);
        $pdf->SetTextColor(255, 255, 255);
        $pdf->Cell(120, 10, 'PGS CENTRUM  |  ' . strtoupper($unitName), 0, 0, 'L');

        $pdf->SetFont('helvetica', '', 9);
        $pdf->SetTextColor(220, 220, 220);
        $pdf->Cell(0, 10, "{$from} to {$to}", 0, 0, 'R');
    }

    private function resolveImagePath(string $webRoot, string $relPath): ?string
    {
        $rel = ltrim(str_replace('\\', '/', $relPath), '/');
        $candidates = [
            $webRoot . '/' . $rel,
            $webRoot . '/uploads/' . $rel,
            $webRoot . '/admin/' . $rel,
        ];
        foreach ($candidates as $cand) {
            if (is_file($cand)) {
                return $cand;
            }
        }
        return null;
    }
}
