<?php

declare(strict_types=1);

namespace Pgs\Reports;

use Pgs\Auth\Principal;
use Pgs\Core\Db;

final class TasksReportPdf extends PdfBase
{
    public function render(Principal $p, int $unitId, string $from, string $to, string $lang = 'en'): array
    {
        $pdo = Db::pdo();

        // Load unit info
        $uStmt = $pdo->prepare('SELECT id, nombre, ubicacion FROM tbl_unidades WHERE id = :id');
        $uStmt->execute([':id' => $unitId]);
        $unit = $uStmt->fetch(\PDO::FETCH_ASSOC);
        $unitName = $unit ? (string) $unit['nombre'] : "Property #{$unitId}";

        // Query tasks for unit and date range
        $stmt = $pdo->prepare(
            "SELECT t.*,
                    s.name_en AS service_name_en,
                    s.name_es AS service_name_es,
                    e.nombre AS tech_name,
                    t.requested_by_name AS req_name
             FROM tec_tasks t
             LEFT JOIN tec_services s ON s.id = t.service_id
             LEFT JOIN tec_employee e ON e.id = t.assignee_employee_id
             WHERE t.unidad_id = :u
               AND t.created_at BETWEEN :f1 AND :f2
             ORDER BY t.created_at DESC, t.id DESC"
        );
        $stmt->execute([
            ':u' => $unitId,
            ':f1' => $from . ' 00:00:00',
            ':f2' => $to . ' 23:59:59',
        ]);
        $tasks = $stmt->fetchAll(\PDO::FETCH_ASSOC);

        $pdf = $this->createTcpdf("Tasks Report - {$unitName}", "Tasks Report from {$from} to {$to}");

        // --- COVER PAGE ---
        $pdf->AddPage();
        $logoPath = dirname(__DIR__, 4) . '/assets/img/pgsinfo.png';
        if (is_file($logoPath)) {
            $pdf->Image($logoPath, 70, 35, 70, 0, 'PNG');
        }

        $pdf->SetY(85);
        $pdf->SetFont('helvetica', 'B', 22);
        $pdf->SetTextColor(11, 15, 25);
        $pdf->Cell(0, 12, 'TASKS & WORK ORDERS REPORT', 0, 1, 'C');

        // Red line accent #E10600
        $pdf->SetDrawColor(225, 6, 0);
        $pdf->SetLineWidth(1.2);
        $pdf->Line(60, $pdf->GetY(), 150, $pdf->GetY());
        $pdf->Ln(6);

        $pdf->SetFont('helvetica', 'B', 15);
        $pdf->SetTextColor(225, 6, 0);
        $pdf->Cell(0, 9, strtoupper($unitName), 0, 1, 'C');

        $pdf->SetFont('helvetica', '', 12);
        $pdf->SetTextColor(80, 80, 80);
        $pdf->Cell(0, 8, "Period: {$from} to {$to}", 0, 1, 'C');

        // Summary counts
        $byStatus = [];
        foreach ($tasks as $t) {
            $st = (string) $t['status'];
            $byStatus[$st] = ($byStatus[$st] ?? 0) + 1;
        }

        $pdf->Cell(0, 8, 'Total Tasks Recorded: ' . count($tasks), 0, 1, 'C');

        $pdf->Ln(10);
        $pdf->SetFont('helvetica', 'B', 11);
        $pdf->SetTextColor(11, 15, 25);
        $pdf->Cell(0, 7, 'Status Breakdown:', 0, 1, 'C');
        $pdf->SetFont('helvetica', '', 10);
        $pdf->SetTextColor(100, 100, 100);

        $statusSummary = [];
        foreach ($byStatus as $st => $count) {
            $statusSummary[] = ucfirst(str_replace('_', ' ', $st)) . ": {$count}";
        }
        $pdf->Cell(0, 6, empty($statusSummary) ? 'No tasks' : implode('   |   ', $statusSummary), 0, 1, 'C');

        $pdf->SetY(220);
        $pdf->SetFont('helvetica', '', 10);
        $pdf->SetTextColor(120, 120, 120);
        $pdf->Cell(0, 6, 'Generated by: ' . ($p->isSystemAdmin() ? 'Super Administrator' : 'Authorized User'), 0, 1, 'C');
        $pdf->Cell(0, 6, 'Generated Date: ' . date('Y-m-d H:i:s T'), 0, 1, 'C');
        $pdf->Cell(0, 6, 'Confidential Property Report - PGS Centrum', 0, 1, 'C');

        // --- TASKS CONTENT ---
        $pdf->AddPage();
        $this->renderHeaderBar($pdf, $unitName, $from, $to);
        $pdf->SetY(32);

        if (empty($tasks)) {
            $pdf->SetFont('helvetica', 'I', 12);
            $pdf->SetTextColor(120, 120, 120);
            $pdf->Cell(0, 15, 'No tasks found for this property in the selected date range.', 0, 1, 'C');
        } else {
            foreach ($tasks as $idx => $t) {
                // If remaining space on page is small, add new page
                if ($pdf->GetY() > 240) {
                    $pdf->AddPage();
                    $this->renderHeaderBar($pdf, $unitName, $from, $to);
                    $pdf->SetY(32);
                }

                $taskY = $pdf->GetY();
                $code = (string) $t['code'];
                $title = (string) $t['title'];
                $status = strtoupper((string) $t['status']);
                $priority = strtoupper((string) ($t['priority'] ?? 'NORMAL'));
                $dueDate = !empty($t['due_date']) ? (string) $t['due_date'] : 'None';
                $created = substr((string) $t['created_at'], 0, 10);
                $tech = !empty($t['tech_name']) ? (string) $t['tech_name'] : 'Unassigned';
                $serviceName = ($lang === 'es' && !empty($t['service_name_es'])) ? (string) $t['service_name_es'] : ((string) ($t['service_name_en'] ?? 'General'));

                // Card header box
                $pdf->SetFillColor(245, 247, 250);
                $pdf->Rect(15, $taskY, 180, 8, 'F');
                $pdf->SetFont('helvetica', 'B', 10);
                $pdf->SetTextColor(225, 6, 0);
                $pdf->SetXY(17, $taskY);
                $pdf->Cell(40, 8, $code, 0, 0, 'L');

                $pdf->SetFont('helvetica', 'B', 10);
                $pdf->SetTextColor(11, 15, 25);
                $pdf->Cell(85, 8, substr($title, 0, 45), 0, 0, 'L');

                $pdf->SetFont('helvetica', 'B', 9);
                if ($status === 'COMPLETED') {
                    $pdf->SetTextColor(22, 101, 52); // green
                } elseif ($status === 'IN_PROGRESS') {
                    $pdf->SetTextColor(30, 64, 175); // blue
                } elseif ($status === 'CANCELLED') {
                    $pdf->SetTextColor(150, 150, 150);
                } else {
                    $pdf->SetTextColor(202, 138, 4); // yellow/orange
                }
                $pdf->Cell(0, 8, $status, 0, 1, 'R');

                // Card metadata
                $pdf->SetFont('helvetica', '', 9);
                $pdf->SetTextColor(80, 80, 80);
                $pdf->SetX(17);
                $metaText = "Service: {$serviceName}   |   Priority: {$priority}   |   Due: {$dueDate}   |   Created: {$created}   |   Assigned: {$tech}";
                $pdf->Cell(0, 6, $metaText, 0, 1, 'L');

                // Description
                if (!empty($t['description'])) {
                    $pdf->SetFont('helvetica', '', 8.5);
                    $pdf->SetTextColor(50, 50, 50);
                    $pdf->SetX(17);
                    $desc = mb_strimwidth((string) $t['description'], 0, 200, '...');
                    $pdf->MultiCell(176, 5, "Description: " . $desc, 0, 'L');
                }

                if (!empty($t['resolution_notes'])) {
                    $pdf->SetFont('helvetica', 'I', 8.5);
                    $pdf->SetTextColor(22, 101, 52);
                    $pdf->SetX(17);
                    $notes = mb_strimwidth((string) $t['resolution_notes'], 0, 180, '...');
                    $pdf->MultiCell(176, 5, "Resolution: " . $notes, 0, 'L');
                }

                $pdf->Ln(4);
                $pdf->SetDrawColor(220, 220, 220);
                $pdf->SetLineWidth(0.3);
                $pdf->Line(15, $pdf->GetY(), 195, $pdf->GetY());
                $pdf->Ln(4);
            }
        }

        return $this->saveToStorage($pdf, 'tasks_report_' . $unitId);
    }

    private function renderHeaderBar(\TCPDF $pdf, string $unitName, string $from, string $to): void
    {
        $pdf->Rect(0, 0, 210, 22, 'F', [], [11, 15, 25]);
        $pdf->Rect(0, 22, 210, 2, 'F', [], [225, 6, 0]);

        $pdf->SetXY(15, 6);
        $pdf->SetFont('helvetica', 'B', 11);
        $pdf->SetTextColor(255, 255, 255);
        $pdf->Cell(120, 10, 'PGS CENTRUM  |  ' . strtoupper($unitName) . '  |  TASKS', 0, 0, 'L');

        $pdf->SetFont('helvetica', '', 9);
        $pdf->SetTextColor(220, 220, 220);
        $pdf->Cell(0, 10, "{$from} to {$to}", 0, 0, 'R');
    }
}
