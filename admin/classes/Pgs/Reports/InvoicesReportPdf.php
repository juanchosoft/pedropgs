<?php

declare(strict_types=1);

namespace Pgs\Reports;

use Pgs\Auth\Principal;
use Pgs\Core\Db;

final class InvoicesReportPdf extends PdfBase
{
    public function render(Principal $p, int $unitId, string $from, string $to, string $lang = 'en'): array
    {
        $pdo = Db::pdo();

        // Load unit info
        $uStmt = $pdo->prepare('SELECT id, nombre, ubicacion FROM tbl_unidades WHERE id = :id');
        $uStmt->execute([':id' => $unitId]);
        $unit = $uStmt->fetch(\PDO::FETCH_ASSOC);
        $unitName = $unit ? (string) $unit['nombre'] : "Property #{$unitId}";

        // Query invoices for unit and date range
        $stmt = $pdo->prepare(
            "SELECT i.*
             FROM tec_invoices i
             WHERE i.unidad_id = :u
               AND i.issue_date BETWEEN :f1 AND :f2
             ORDER BY i.issue_date DESC, i.id DESC"
        );
        $stmt->execute([
            ':u' => $unitId,
            ':f1' => $from,
            ':f2' => $to,
        ]);
        $invoices = $stmt->fetchAll(\PDO::FETCH_ASSOC);

        $pdf = $this->createTcpdf("Invoices Report - {$unitName}", "Invoices Report from {$from} to {$to}");

        // --- COVER PAGE ---
        $pdf->AddPage();
        $logoPath = dirname(__DIR__, 4) . '/assets/img/pgsinfo.png';
        if (is_file($logoPath)) {
            $pdf->Image($logoPath, 70, 35, 70, 0, 'PNG');
        }

        $pdf->SetY(85);
        $pdf->SetFont('helvetica', 'B', 22);
        $pdf->SetTextColor(11, 15, 25);
        $pdf->Cell(0, 12, 'BILLING & INVOICES REPORT', 0, 1, 'C');

        // Red line accent #E10600
        $pdf->SetDrawColor(225, 6, 0);
        $pdf->SetLineWidth(1.2);
        $pdf->Line(60, $pdf->GetY(), 150, $pdf->GetY());
        $pdf->Ln(6);

        $pdf->SetFont('helvetica', 'B', 15);
        $pdf->SetTextColor(225, 6, 0);
        $pdf->Cell(0, 9, strtoupper($unitName), 0, 1, 'C');

        $pdf->SetFont('helvetica', '', 12);
        $pdf->SetTextColor(80, 80, 80);
        $pdf->Cell(0, 8, "Period: {$from} to {$to}", 0, 1, 'C');

        // Totals calculation
        $totalBilled = 0.0;
        $totalPaid = 0.0;
        $totalOutstanding = 0.0;
        $countInvoices = count($invoices);

        foreach ($invoices as $inv) {
            if ($inv['payment_status'] === 'void') {
                continue;
            }
            $amt = (float) $inv['amount'];
            $paid = (float) ($inv['amount_paid'] ?? 0.0);
            $totalBilled += $amt;
            $totalPaid += $paid;
            $totalOutstanding += max(0.0, $amt - $paid);
        }

        $pdf->Ln(6);
        $pdf->SetFont('helvetica', 'B', 11);
        $pdf->SetTextColor(11, 15, 25);
        $pdf->Cell(0, 7, 'Financial Summary:', 0, 1, 'C');

        $pdf->SetFont('helvetica', '', 10);
        $pdf->SetTextColor(80, 80, 80);
        $pdf->Cell(0, 6, "Total Invoices: {$countInvoices}", 0, 1, 'C');
        $pdf->Cell(0, 6, sprintf('Total Billed: $%.2f   |   Total Paid: $%.2f', $totalBilled, $totalPaid), 0, 1, 'C');

        $pdf->SetFont('helvetica', 'B', 11);
        $pdf->SetTextColor(225, 6, 0);
        $pdf->Cell(0, 7, sprintf('Outstanding Balance: $%.2f', $totalOutstanding), 0, 1, 'C');

        $pdf->SetY(220);
        $pdf->SetFont('helvetica', '', 10);
        $pdf->SetTextColor(120, 120, 120);
        $pdf->Cell(0, 6, 'Generated by: ' . ($p->isSystemAdmin() ? 'Super Administrator' : 'Authorized Representative'), 0, 1, 'C');
        $pdf->Cell(0, 6, 'Generated Date: ' . date('Y-m-d H:i:s T'), 0, 1, 'C');
        $pdf->Cell(0, 6, 'Confidential Financial Document - PGS Centrum', 0, 1, 'C');

        // --- INVOICES CONTENT ---
        $pdf->AddPage();
        $this->renderHeaderBar($pdf, $unitName, $from, $to);
        $pdf->SetY(32);

        if (empty($invoices)) {
            $pdf->SetFont('helvetica', 'I', 12);
            $pdf->SetTextColor(120, 120, 120);
            $pdf->Cell(0, 15, 'No invoices found for this property in the selected date range.', 0, 1, 'C');
        } else {
            // Table Header
            $pdf->SetFillColor(11, 15, 25);
            $pdf->SetTextColor(255, 255, 255);
            $pdf->SetFont('helvetica', 'B', 9);
            $pdf->Cell(35, 8, ' Invoice #', 0, 0, 'L', true);
            $pdf->Cell(25, 8, 'Issue Date', 0, 0, 'C', true);
            $pdf->Cell(25, 8, 'Due Date', 0, 0, 'C', true);
            $pdf->Cell(30, 8, 'Amount', 0, 0, 'R', true);
            $pdf->Cell(30, 8, 'Paid', 0, 0, 'R', true);
            $pdf->Cell(35, 8, 'Status ', 0, 1, 'R', true);

            $fill = false;
            foreach ($invoices as $inv) {
                if ($pdf->GetY() > 250) {
                    $pdf->AddPage();
                    $this->renderHeaderBar($pdf, $unitName, $from, $to);
                    $pdf->SetY(32);

                    $pdf->SetFillColor(11, 15, 25);
                    $pdf->SetTextColor(255, 255, 255);
                    $pdf->SetFont('helvetica', 'B', 9);
                    $pdf->Cell(35, 8, ' Invoice #', 0, 0, 'L', true);
                    $pdf->Cell(25, 8, 'Issue Date', 0, 0, 'C', true);
                    $pdf->Cell(25, 8, 'Due Date', 0, 0, 'C', true);
                    $pdf->Cell(30, 8, 'Amount', 0, 0, 'R', true);
                    $pdf->Cell(30, 8, 'Paid', 0, 0, 'R', true);
                    $pdf->Cell(35, 8, 'Status ', 0, 1, 'R', true);
                    $fill = false;
                }

                $status = strtoupper((string) ($inv['payment_status'] ?? 'PENDING'));
                $amount = (float) $inv['amount'];
                $paid = (float) ($inv['amount_paid'] ?? 0.0);

                $pdf->SetFillColor($fill ? 248 : 255, $fill ? 249 : 255, $fill ? 250 : 255);
                $pdf->SetFont('helvetica', 'B', 9);
                $pdf->SetTextColor(11, 15, 25);
                $pdf->Cell(35, 7, ' ' . (string) $inv['invoice_number'], 0, 0, 'L', true);

                $pdf->SetFont('helvetica', '', 9);
                $pdf->SetTextColor(80, 80, 80);
                $pdf->Cell(25, 7, (string) $inv['issue_date'], 0, 0, 'C', true);
                $pdf->Cell(25, 7, (string) $inv['due_date'], 0, 0, 'C', true);

                $pdf->SetFont('helvetica', 'B', 9);
                $pdf->SetTextColor(11, 15, 25);
                $pdf->Cell(30, 7, sprintf('$%.2f', $amount), 0, 0, 'R', true);

                $pdf->SetFont('helvetica', '', 9);
                $pdf->SetTextColor(40, 40, 40);
                $pdf->Cell(30, 7, sprintf('$%.2f', $paid), 0, 0, 'R', true);

                $pdf->SetFont('helvetica', 'B', 8.5);
                if ($status === 'PAID') {
                    $pdf->SetTextColor(22, 101, 52);
                } elseif ($status === 'OVERDUE') {
                    $pdf->SetTextColor(225, 6, 0);
                } elseif ($status === 'PARTIALLY_PAID') {
                    $pdf->SetTextColor(30, 64, 175);
                } elseif ($status === 'VOID') {
                    $pdf->SetTextColor(150, 150, 150);
                } else {
                    $pdf->SetTextColor(202, 138, 4);
                }
                $pdf->Cell(35, 7, $status . ' ', 0, 1, 'R', true);

                $fill = !$fill;
            }

            // Bottom border
            $pdf->SetDrawColor(200, 200, 200);
            $pdf->SetLineWidth(0.5);
            $pdf->Line(15, $pdf->GetY(), 195, $pdf->GetY());
            $pdf->Ln(5);

            // Summary box at bottom
            $pdf->SetFillColor(245, 247, 250);
            $pdf->Rect(110, $pdf->GetY(), 85, 22, 'F');
            $boxY = $pdf->GetY() + 2;
            $pdf->SetXY(112, $boxY);
            $pdf->SetFont('helvetica', '', 9);
            $pdf->SetTextColor(80, 80, 80);
            $pdf->Cell(45, 5, 'Total Invoiced:', 0, 0, 'L');
            $pdf->Cell(35, 5, sprintf('$%.2f', $totalBilled), 0, 1, 'R');

            $pdf->SetX(112);
            $pdf->Cell(45, 5, 'Total Payments:', 0, 0, 'L');
            $pdf->Cell(35, 5, sprintf('$%.2f', $totalPaid), 0, 1, 'R');

            $pdf->SetX(112);
            $pdf->SetFont('helvetica', 'B', 9.5);
            $pdf->SetTextColor(225, 6, 0);
            $pdf->Cell(45, 6, 'Balance Due:', 0, 0, 'L');
            $pdf->Cell(35, 6, sprintf('$%.2f', $totalOutstanding), 0, 1, 'R');
        }

        return $this->saveToStorage($pdf, 'invoices_report_' . $unitId);
    }

    private function renderHeaderBar(\TCPDF $pdf, string $unitName, string $from, string $to): void
    {
        $pdf->Rect(0, 0, 210, 22, 'F', [], [11, 15, 25]);
        $pdf->Rect(0, 22, 210, 2, 'F', [], [225, 6, 0]);

        $pdf->SetXY(15, 6);
        $pdf->SetFont('helvetica', 'B', 11);
        $pdf->SetTextColor(255, 255, 255);
        $pdf->Cell(120, 10, 'PGS CENTRUM  |  ' . strtoupper($unitName) . '  |  INVOICES', 0, 0, 'L');

        $pdf->SetFont('helvetica', '', 9);
        $pdf->SetTextColor(220, 220, 220);
        $pdf->Cell(0, 10, "{$from} to {$to}", 0, 0, 'R');
    }
}
